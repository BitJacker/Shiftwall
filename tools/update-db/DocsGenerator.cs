using System.Globalization;
using System.Text;
using Shiftwall.Core.Data;

namespace Shiftwall.UpdateDb;

/// <summary>Generates docs/SOURCES.md and docs/supported-models.md from the database.</summary>
internal static class DocsGenerator
{
    public static string Sources(ModelDatabase db)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Sources");
        sb.AppendLine();
        sb.AppendLine("<!-- Generated by `dotnet run --project tools/update-db -- gen-docs`. Do not edit by hand. -->");
        sb.AppendLine();
        sb.AppendLine("Every datum in Shiftwall's model database comes from an official Fortinet source and records the date it");
        sb.AppendLine("was last checked. Data without a reliable source is marked **unverified**: the app shows a warning and");
        sb.AppendLine("never relies on it silently. A real factory-default backup of the target model always takes precedence.");
        sb.AppendLine();
        sb.AppendLine("Accepted hosts: " + string.Join(", ", DatabaseValidator.OfficialHosts.Select(h => $"`{h}`")) +
                      " (S3 only for attachments linked from docs.fortinet.com).");
        sb.AppendLine();

        var verifiedFields = 0;
        var unverifiedFields = 0;
        void Count<T>(Sourced<T> s) { if (s.IsVerified) verifiedFields++; else unverifiedFields++; }
        foreach (var m in db.Models) { Count(m.Interfaces); Count(m.HasDisk); Count(m.DefaultSwitches); }
        foreach (var r in db.Releases) { Count(r.Build); Count(r.ReleaseDate); Count(r.SupportedModels); }

        sb.AppendLine("## Summary");
        sb.AppendLine();
        sb.AppendLine($"- Models: **{db.Models.Count}**");
        sb.AppendLine($"- FortiOS releases: **{db.Releases.Count}** ({db.Releases[0].Version} – {db.Releases[^1].Version})");
        sb.AppendLine($"- Fields verified: **{verifiedFields}**, unverified: **{unverifiedFields}**");
        sb.AppendLine($"- Upgrade paths: {(db.UpgradePaths.Paths.Count == 0 ? "none listed — see below" : db.UpgradePaths.Paths.Count.ToString(CultureInfo.InvariantCulture))}");
        sb.AppendLine();

        sb.AppendLine("## Upgrade paths");
        sb.AppendLine();
        var up = db.UpgradePaths.PublishedInConsultableForm;
        sb.AppendLine(up.Note ?? "");
        sb.AppendLine();
        sb.AppendLine($"Official tool: <{db.UpgradePaths.OfficialToolUrl}>");
        sb.AppendLine();
        AppendSources(sb, up.Sources);

        sb.AppendLine("## Models");
        sb.AppendLine();
        foreach (var m in db.Models.OrderBy(m => m.Id, StringComparer.Ordinal))
        {
            sb.AppendLine($"### {m.Id} — {m.DisplayName}");
            sb.AppendLine();
            if (m.Note is not null) { sb.AppendLine(m.Note); sb.AppendLine(); }
            AppendField(sb, "Interfaces", m.Interfaces, v => string.Join(", ", v.Select(i => $"`{i.Name}`")));
            AppendField(sb, "Disk", m.HasDisk, v => v == true ? "yes" : "no");
            AppendField(sb, "Default hardware/virtual switch", m.DefaultSwitches,
                v => v.Count == 0 ? "none" : string.Join("; ", v.Select(s => $"`{s.Name}`: {string.Join(", ", s.Members)}")));
        }

        sb.AppendLine("## FortiOS releases");
        sb.AppendLine();
        sb.AppendLine("Build and supported models: release notes, *Introduction and supported models*. Release date: date of the");
        sb.AppendLine("*Initial release* row in the release notes *Change Log* (publication date of the release notes).");
        sb.AppendLine();
        sb.AppendLine("| Version | Build | Release date | Models | Release notes | Change log | Verified on |");
        sb.AppendLine("|---|---|---|---|---|---|---|");
        foreach (var r in db.Releases.Reverse())
        {
            var intro = r.Build.Sources.FirstOrDefault()?.Url ?? r.SupportedModels.Sources.FirstOrDefault()?.Url;
            var cl = r.ReleaseDate.Sources.FirstOrDefault()?.Url;
            var verified = r.Build.Sources.Concat(r.ReleaseDate.Sources).Concat(r.SupportedModels.Sources).Select(s => s.VerifiedOn).DefaultIfEmpty().Max();
            sb.AppendLine(CultureInfo.InvariantCulture,
                $"| {r.Version} | {Mark(r.Build, r.Build.Value)} | {Mark(r.ReleaseDate, r.ReleaseDate.Value?.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture))} | {r.SupportedModels.Value?.Count.ToString(CultureInfo.InvariantCulture) ?? "⚠ unverified"} | {Link(intro)} | {Link(cl)} | {(verified == default ? "—" : verified.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture))} |");
        }

        return sb.ToString();
    }

    public const string TableStart = "<!-- models:start (generated by update-db gen-docs, do not edit) -->";
    public const string TableEnd = "<!-- models:end -->";

    public static string SupportedModels(ModelDatabase db)
    {
        var sb = new StringBuilder();
        sb.AppendLine("<!-- Generated by `dotnet run --project tools/update-db -- gen-docs`. Do not edit by hand. -->");
        sb.AppendLine();
        sb.Append(ModelsTable(db, "SOURCES.md", italian: false));
        return sb.ToString();
    }

    /// <summary>Supported models table with its legend; <paramref name="sourcesLink"/> is relative to the target file.</summary>
    public static string ModelsTable(ModelDatabase db, string sourcesLink, bool italian)
    {
        var sb = new StringBuilder();
        sb.AppendLine(italian
            ? "| Modello | Interfacce | Disco | Switch di default | FortiOS (release notes) |"
            : "| Model | Interfaces | Disk | Default switch | FortiOS (release notes) |");
        sb.AppendLine("|---|---|---|---|---|");
        var yes = italian ? "sì" : "yes";
        var none = italian ? "nessuno" : "none";
        foreach (var m in db.Models.OrderBy(m => m.Platform).ThenBy(m => m.Id, StringComparer.Ordinal))
        {
            var versions = db.ReleasesSupporting(m.Id).Select(r => FortiOsVersion.Parse(r.Version)).ToList();
            var range = versions.Count == 0 ? "—" : $"{versions.Min()} – {versions.Max()}";
            sb.AppendLine($"| {m.Id} | {Status(m.Interfaces, m.Interfaces.Value?.Count.ToString(CultureInfo.InvariantCulture))} | {Status(m.HasDisk, m.HasDisk.Value == true ? yes : "no")} | {Status(m.DefaultSwitches, m.DefaultSwitches.Value is { Count: > 0 } s ? string.Join(", ", s.Select(x => x.Name)) : none)} | {range} |");
        }

        sb.AppendLine();
        sb.AppendLine(italian
            ? $"✅ verificato da una fonte ufficiale · ⚠ non verificato (vedi [SOURCES.md]({sourcesLink}))"
            : $"✅ verified from an official source · ⚠ unverified (see [SOURCES.md]({sourcesLink}))");
        return sb.ToString();
    }

    /// <summary>Replaces the text between <see cref="TableStart"/> and <see cref="TableEnd"/>.</summary>
    public static string ReplaceTable(string document, string table)
    {
        var start = document.IndexOf(TableStart, StringComparison.Ordinal);
        var end = document.IndexOf(TableEnd, StringComparison.Ordinal);
        if (start < 0 || end < start)
        {
            throw new InvalidOperationException($"Markers '{TableStart}' and '{TableEnd}' not found.");
        }

        var newline = document.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        var body = table.ReplaceLineEndings(newline);
        return string.Concat(document.AsSpan(0, start + TableStart.Length), newline, body, document.AsSpan(end));
    }

    private static string Status<T>(Sourced<T> s, string? text) => s.IsVerified ? $"✅ {text}" : "⚠";

    private static string Mark<T>(Sourced<T> s, string? text) => s.IsVerified ? text ?? "" : "⚠ unverified";

    private static string Cite(SourceRef src) => src.Url is null
        ? $"{src.Title} (factory-default backup examined locally, not published)"
        : $"[{src.Title}]({src.Url})";

    private static string Link(string? url) => url is null ? "—" : $"[link]({url})";

    private static void AppendField<T>(StringBuilder sb, string label, Sourced<T> s, Func<T, string> render)
    {
        if (s.IsVerified && s.Value is { } v)
        {
            sb.AppendLine($"- **{label}:** {render(v)}");
        }
        else
        {
            sb.AppendLine($"- **{label}:** ⚠ unverified — {s.Note}");
        }

        foreach (var src in s.Sources)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"  - {Cite(src)} — verified {src.VerifiedOn:yyyy-MM-dd}{(src.Note is null ? "" : " — " + src.Note)}");
        }

        if (s.IsVerified && s.Note is not null)
        {
            sb.AppendLine($"  - Note: {s.Note}");
        }

        sb.AppendLine();
    }

    private static void AppendSources(StringBuilder sb, IEnumerable<SourceRef> sources)
    {
        foreach (var src in sources)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"- {Cite(src)} — verified {src.VerifiedOn:yyyy-MM-dd}{(src.Note is null ? "" : " — " + src.Note)}");
        }

        sb.AppendLine();
    }
}
