using Shiftwall.Core.Config;

namespace Shiftwall.Features.Toolbox.TwoFactor;

/// <summary>
/// Settings of the tables this module touches, as a comparable state: <c>user local</c> entries per VDOM,
/// <c>system admin</c> entries and the <c>system global</c> settings. Used for the dry run and to prove that a batch
/// followed by its rollback gives back the original values.
/// </summary>
public sealed class AccountState
{
    private static readonly string[] Tables = ["user local", "system admin"];
    private static readonly string[] SettingsBlocks = ["system global"];

    /// <summary>(scope, table, entry) → field → values. Scope: "" (single VDOM), "global" or "vdom:&lt;name&gt;".</summary>
    public Dictionary<(string Scope, string Table, string Entry), Dictionary<string, string[]>> Entries { get; } = [];

    /// <summary>(scope, settings block) → field → values.</summary>
    public Dictionary<(string Scope, string Block), Dictionary<string, string[]>> Settings { get; } = [];

    public static AccountState FromConfig(ConfigDocument doc)
    {
        ArgumentNullException.ThrowIfNull(doc);
        var state = new AccountState();
        var globalScope = doc.IsMultiVdom ? "global" : "";
        foreach (var (vdom, scope) in ConfigTables.VdomScopes(doc))
        {
            var name = vdom is null ? "" : "vdom:" + vdom;
            foreach (var e in ConfigTables.Entries(scope, "user local")) state.Entries[(name, "user local", e.Key)] = Fields(e);
        }

        foreach (var e in ConfigTables.Entries(doc.GlobalScope, "system admin")) state.Entries[(globalScope, "system admin", e.Key)] = Fields(e);
        foreach (var block in SettingsBlocks)
        {
            if (ConfigTables.Settings(doc.GlobalScope, block) is { } b) state.Settings[(globalScope, block)] = Fields(b);
        }

        return state;
    }

    private static Dictionary<string, string[]> Fields(ConfigContainer c)
    {
        var d = new Dictionary<string, string[]>(StringComparer.Ordinal);
        foreach (var f in c.Fields)
        {
            if (f.Verb == "set") d[f.Name] = [.. f.Values];
            else if (f.Verb == "unset") d.Remove(f.Name);
        }

        return d;
    }

    public AccountState Clone()
    {
        var c = new AccountState();
        foreach (var (k, v) in Entries) c.Entries[k] = new Dictionary<string, string[]>(v, StringComparer.Ordinal);
        foreach (var (k, v) in Settings) c.Settings[k] = new Dictionary<string, string[]>(v, StringComparer.Ordinal);
        return c;
    }

    /// <summary>Same entries with the same field values (order of fields and entries ignored).</summary>
    public bool SameAs(AccountState other) =>
        Same(Entries, other.Entries) && Same(Settings, other.Settings);

    private static bool Same<TKey>(Dictionary<TKey, Dictionary<string, string[]>> a, Dictionary<TKey, Dictionary<string, string[]>> b)
        where TKey : notnull =>
        a.Count == b.Count && a.All(kv => b.TryGetValue(kv.Key, out var o) && kv.Value.Count == o.Count
            && kv.Value.All(f => o.TryGetValue(f.Key, out var v) && v.SequenceEqual(f.Value, StringComparer.Ordinal)));

    /// <summary>Applies a script generated by this module (config/edit/set/unset/delete/next/end) to a copy of the state.</summary>
    public AccountState Apply(string script)
    {
        var state = Clone();
        var stack = new Stack<Frame>();
        foreach (var st in ConfigLexer.Lex(script))
        {
            switch (st.Kind)
            {
                case StatementKind.Config:
                {
                    var path = string.Join(' ', st.Tokens.Skip(1).Select(t => t.Value));
                    var scope = stack.FirstOrDefault(f => f.Kind == FrameKind.Scope)?.Name ?? "";
                    stack.Push(stack.Count == 0 && path == "global" ? new Frame(FrameKind.Scope, "global", null)
                        : stack.Count == 0 && path == "vdom" ? new Frame(FrameKind.VdomList, "", null)
                        : new Frame(FrameKind.Table, path, scope));
                    break;
                }

                case StatementKind.Edit:
                {
                    var key = st.Tokens.Count > 1 ? st.Tokens[1].Value : "";
                    var top = stack.Peek();
                    if (top.Kind == FrameKind.VdomList)
                    {
                        stack.Push(new Frame(FrameKind.Scope, "vdom:" + key, null));
                        break;
                    }

                    var id = (top.Scope!, top.Name, key);
                    if (!state.Entries.ContainsKey(id)) state.Entries[id] = new(StringComparer.Ordinal);
                    stack.Push(new Frame(FrameKind.Entry, key, top.Scope) { Table = top.Name });
                    break;
                }

                case StatementKind.Next:
                case StatementKind.End:
                    if (stack.Count > 0) stack.Pop();
                    break;

                case StatementKind.Field:
                {
                    var top = stack.Peek();
                    var fields = top.Kind == FrameKind.Entry
                        ? state.Entries[(top.Scope!, top.Table!, top.Name)]
                        : SettingsOf(state, (top.Scope!, top.Name));
                    var name = st.FieldName!;
                    if (st.Verb == "set") fields[name] = [.. st.FieldValues.Select(t => t.Value)];
                    else if (st.Verb == "unset") fields.Remove(name);
                    break;
                }

                case StatementKind.Other when st.Verb == "delete":
                {
                    var top = stack.Peek();
                    state.Entries.Remove((top.Scope!, top.Name, st.Tokens[1].Value));
                    break;
                }
            }
        }

        // Only the tables this module reads are compared.
        foreach (var k in state.Entries.Keys.Where(k => !Tables.Contains(k.Table)).ToList()) state.Entries.Remove(k);
        foreach (var k in state.Settings.Keys.Where(k => !SettingsBlocks.Contains(k.Block)).ToList()) state.Settings.Remove(k);
        return state;
    }

    private static Dictionary<string, string[]> SettingsOf(AccountState s, (string, string) key)
    {
        if (!s.Settings.TryGetValue(key, out var d)) s.Settings[key] = d = new(StringComparer.Ordinal);
        return d;
    }

    private enum FrameKind { Scope, VdomList, Table, Entry }

    private sealed record Frame(FrameKind Kind, string Name, string? Scope)
    {
        public string? Table { get; init; }
    }
}
