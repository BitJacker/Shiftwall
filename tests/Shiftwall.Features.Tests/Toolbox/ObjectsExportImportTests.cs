public sealed class UnusedObjectsTests
{
    [Fact]
    public void FindsUnusedObjects_IncludingMembersOfUnusedGroups()
    {
        var unused = UnusedObjects.Find(Tb.Doc("site-a.fgtcfg"));
        var names = unused.Select(u => u.Name).ToList();
        Assert.Contains("grp-old", names);
        Assert.Contains("old-printer", names);
        Assert.Contains("old-nas", names);
        Assert.True(unused.Single(u => u.Name == "old-nas").OnlyUsedByUnusedGroups);

        // grp-servers is never referenced; srv-web is referenced only by grp-servers.
        Assert.False(unused.Single(u => u.Name == "grp-servers").OnlyUsedByUnusedGroups);
        Assert.True(unused.Single(u => u.Name == "srv-web").OnlyUsedByUnusedGroups);

        // Used: referenced by policies, groups or VIPs.
        foreach (var used in new[] { "all", "net-lan", "net-branch", "updates", "HTTPS", "app-8443", "ALL", "always", "office-hours" })
        {
            Assert.DoesNotContain(used, names);
        }
    }

    [Fact]
    public void ExcludedNames_AreNeverReported()
    {
        var unused = UnusedObjects.Find(Tb.Doc("site-a.fgtcfg"), new HashSet<string> { "old-nas" });
        Assert.DoesNotContain(unused, u => u.Name == "old-nas");
    }

    [Fact]
    public void Script_DeletesGroupsBeforeMembers()
    {
        var unused = UnusedObjects.Find(Tb.Doc("site-a.fgtcfg"));
        var script = UnusedObjects.Script(unused, multiVdom: false, "Generated by Shiftwall\nreview before applying");
        Assert.StartsWith("# Generated by Shiftwall\n# review before applying\n", script);
        Assert.True(script.IndexOf("config firewall addrgrp", StringComparison.Ordinal) < script.IndexOf("config firewall address\n", StringComparison.Ordinal));
        Assert.Contains("    delete \"old-printer\"\n", script);
        var parsed = ConfigParser.Parse(script);
        Assert.DoesNotContain(parsed.Diagnostics, d => d.Severity == DiagnosticSeverity.Error);
    }

    [Fact]
    public void MultiVdom_ScriptEntersEachVdom()
    {
        var script = UnusedObjects.Script([new UnusedObject("branch", "firewall address", "x", false)], multiVdom: true, "h");
        Assert.Contains("config vdom\n    edit \"branch\"\n        config firewall address\n            delete \"x\"\n        end\n    next\nend\n", script);
    }
}

public sealed class ExportTests
{
    [Fact]
    public void Tables_ResolveDocumentedDefaults()
    {
        var tables = ConfigExport.Build(Tb.Doc("site-a.fgtcfg"), CultureInfo.GetCultureInfo("en"));
        var policies = tables[0];
        Assert.Equal("Policies", policies.Name);
        var p4 = policies.Rows.Single(r => r[1] == "4");
        Assert.Equal("enable", p4[3]);   // status default
        Assert.Equal("disable", p4[11]); // nat default
        Assert.Equal("disable", p4[14]); // logtraffic as set
        var p1 = policies.Rows.Single(r => r[1] == "1");
        Assert.Equal("utm", p1[14]);     // logtraffic default
        Assert.Equal("av-profile=default", policies.Rows.Single(r => r[1] == "3")[13]);

        var addresses = tables[1];
        Assert.Contains(addresses.Rows, r => r[0] == "net-lan" && r[1] == "ipmask" && r[2] == "192.168.10.0/24");
        Assert.Contains(addresses.Rows, r => r[0] == "updates" && r[1] == "fqdn" && r[2] == "updates.example.com");
    }

    [Fact]
    public void Csv_QuotesAndBlocksFormulas()
    {
        var t = new ExportTable("x", ["a", "b"], [["=cmd|' /C calc'!A0", "x,y"], ["he said \"hi\"", "-1"]]);
        var csv = CsvWriter.Write(t);
        Assert.Equal("a,b\r\n'=cmd|' /C calc'!A0,\"x,y\"\r\n\"he said \"\"hi\"\"\",'-1\r\n", csv);
        Assert.Equal(new byte[] { 0xEF, 0xBB, 0xBF }, CsvWriter.ToBytes(csv)[..3]);
    }

    [Fact]
    public void Xlsx_IsAValidPackageWithInlineStrings()
    {
        var tables = ConfigExport.Build(Tb.Doc("site-a.fgtcfg"), CultureInfo.GetCultureInfo("it-IT"));
        var bytes = XlsxWriter.Write(tables);
        using var zip = new ZipArchive(new MemoryStream(bytes));
        Assert.NotNull(zip.GetEntry("[Content_Types].xml"));
        var workbook = XDocument.Load(zip.GetEntry("xl/workbook.xml")!.Open());
        XNamespace ns = "http://schemas.openxmlformats.org/spreadsheetml/2006/main";
        var sheetNames = workbook.Descendants(ns + "sheet").Select(s => (string)s.Attribute("name")!).ToList();
        Assert.Equal(tables.Count, sheetNames.Count);
        Assert.Equal("Policy", sheetNames[0]);

        var sheet1 = XDocument.Load(zip.GetEntry("xl/worksheets/sheet1.xml")!.Open());
        Assert.All(sheet1.Descendants(ns + "c"), c => Assert.Equal("inlineStr", (string)c.Attribute("t")!));
        Assert.Empty(sheet1.Descendants(ns + "f"));
        Assert.Contains(sheet1.Descendants(ns + "t"), t => t.Value == "lan-to-internet");
    }

    [Theory]
    [InlineData(0, "A")]
    [InlineData(25, "Z")]
    [InlineData(26, "AA")]
    [InlineData(701, "ZZ")]
    [InlineData(702, "AAA")]
    public void Xlsx_ColumnNames(int i, string expected) => Assert.Equal(expected, XlsxWriter.Column(i));
}

public sealed class ImportTests
{
    [Fact]
    public void Addresses_FromTemplate()
    {
        var r = CsvImport.Convert(ImportKind.Address, CsvImport.Template(ImportKind.Address));
        Assert.True(r.Ok, string.Join("; ", r.Errors.Select(e => e.Format(CultureInfo.InvariantCulture))));
        Assert.Equal(4, r.Objects);
        Assert.Equal(
            "config firewall address\n" +
            "    edit \"srv-web\"\n        set subnet 192.0.2.10 255.255.255.255\n        set comment \"Web server\"\n    next\n" +
            "    edit \"net-lab\"\n        set subnet 198.51.100.0 255.255.255.0\n    next\n" +
            "    edit \"pool-a\"\n        set type iprange\n        set start-ip 192.0.2.20\n        set end-ip 192.0.2.29\n    next\n" +
            "    edit \"updates\"\n        set type fqdn\n        set fqdn \"update.example.com\"\n    next\n" +
            "end\n", r.Script);
        Assert.DoesNotContain(ConfigParser.Parse(r.Script).Diagnostics, d => d.Severity == DiagnosticSeverity.Error);
    }

    [Theory]
    [InlineData(ImportKind.AddressGroup)]
    [InlineData(ImportKind.Service)]
    [InlineData(ImportKind.ServiceGroup)]
    [InlineData(ImportKind.Vip)]
    public void Templates_AreValid(ImportKind kind)
    {
        var r = CsvImport.Convert(kind, CsvImport.Template(kind));
        Assert.True(r.Ok, string.Join("; ", r.Errors.Select(e => e.Format(CultureInfo.InvariantCulture))));
        Assert.True(r.Objects > 0);
    }

    [Fact]
    public void Services_TcpUdpIcmpIp()
    {
        var r = CsvImport.Convert(ImportKind.Service, CsvImport.Template(ImportKind.Service));
        Assert.Contains("    edit \"dns-alt\"\n        set protocol TCP/UDP/UDP-Lite/SCTP\n        set tcp-portrange 5353\n        set udp-portrange 5353\n    next\n", r.Script);
        Assert.Contains("        set protocol ICMP\n        set icmptype 8\n        set icmpcode 0\n", r.Script);
        Assert.Contains("        set protocol IP\n        set protocol-number 47\n", r.Script);
    }

    [Fact]
    public void SemicolonCsv_AndQuotedValues()
    {
        var r = CsvImport.Convert(ImportKind.AddressGroup, "name;members;comment\r\n\"grp; 1\";a|b;\"Commento con \"\"virgolette\"\"\"\r\n");
        Assert.True(r.Ok);
        Assert.Contains("    edit \"grp; 1\"\n        set member \"a\" \"b\"\n        set comment \"Commento con \\\"virgolette\\\"\"\n", r.Script);
    }

    [Fact]
    public void Errors_AreReportedPerRow_AndNoScriptIsProduced()
    {
        var csv = "name,type,value\nok,ipmask,192.0.2.0/24\nbad,ipmask,192.0.2.1/24\n,ipmask,192.0.2.0/24\nok,ipmask,198.51.100.0/24\nx,iprange,192.0.2.9-192.0.2.1\n" +
                  new string('n', 80) + ",ipmask,192.0.2.0/24\ny,unknown,1\n";
        var r = CsvImport.Convert(ImportKind.Address, csv);
        Assert.False(r.Ok);
        Assert.Equal("", r.Script);
        Assert.Equal(["HostBits", "NameMissing", "NameDuplicate", "BadRange", "NameTooLong", "BadAddressType"], r.Errors.Select(e => e.Code));
        Assert.Equal(3, r.Errors[0].Row);
        Assert.Equal("Riga 3: \"192.0.2.1/24\" ha bit di host impostati: usa l'indirizzo di rete.", r.Errors[0].Format(CultureInfo.GetCultureInfo("it-IT")));
    }

    [Fact]
    public void MissingRequiredColumn()
    {
        var r = CsvImport.Convert(ImportKind.Vip, "name,extip\nv,192.0.2.1\n");
        Assert.Equal(["MissingColumn", "MissingColumn"], r.Errors.Select(e => e.Code));
    }

    [Theory]
    [InlineData("443", true)]
    [InlineData("8000-8080", true)]
    [InlineData("80:1024-65535", true)]
    [InlineData("0", false)]
    [InlineData("65536", false)]
    [InlineData("90-80", false)]
    [InlineData("abc", false)]
    public void PortRanges(string ports, bool ok)
    {
        var r = CsvImport.Convert(ImportKind.Service, $"name,protocol,ports\ns,tcp,{ports}\n");
        Assert.Equal(ok, r.Ok);
    }
}

public sealed class SnippetTests
{
    [Fact]
    public void Vlan()
    {
        var r = SnippetGenerator.Vlan(new VlanInput("vlan30", "internal5", 30, "192.168.30.1/24", Alias: "Ospiti"));
        Assert.True(r.Ok);
        Assert.Equal("config system interface\n    edit \"vlan30\"\n        set vdom \"root\"\n        set ip 192.168.30.1 255.255.255.0\n        set allowaccess ping\n        set alias \"Ospiti\"\n        set role lan\n        set interface \"internal5\"\n        set vlanid 30\n    next\nend\n", r.Script);
    }

    [Fact]
    public void Policy_UsesEdit0AndQuotesLists()
    {
        var r = SnippetGenerator.Policy(new PolicyInput("guest-web", "vlan30", "wan1", "all", "all", "HTTP, HTTPS", "accept", Nat: true, Comment: "Ospiti"));
        Assert.True(r.Ok);
        Assert.Contains("    edit 0\n", r.Script);
        Assert.Contains("        set service \"HTTP\" \"HTTPS\"\n", r.Script);
        Assert.Contains("        set nat enable\n", r.Script);
        Assert.DoesNotContain(ConfigParser.Parse(r.Script).Diagnostics, d => d.Severity == DiagnosticSeverity.Error);
    }

    [Fact]
    public void StaticRoute_RejectsHostBits()
    {
        Assert.True(SnippetGenerator.StaticRoute(new StaticRouteInput("10.20.0.0/16", "192.168.1.254", "internal")).Ok);
        var bad = SnippetGenerator.StaticRoute(new StaticRouteInput("10.20.0.1/16", "192.168.1.254", "internal"));
        Assert.Equal("HostBits", Assert.Single(bad.Errors).Code);
    }

    [Fact]
    public void LocalUser_NeverContainsAPassword()
    {
        var r = SnippetGenerator.LocalUser(new LocalUserInput("mario.rossi"));
        Assert.Contains("set passwd <PASSWORD>", r.Script);
    }

    [Fact]
    public void Vip_ReusesImportValidation()
    {
        Assert.True(SnippetGenerator.Vip(new VipInput("vip1", "wan1", "203.0.113.10", "192.168.1.10", "tcp", "443", "8443")).Ok);
        var bad = SnippetGenerator.Vip(new VipInput("vip1", "wan1", "not-an-ip", "192.168.1.10"));
        Assert.False(bad.Ok);
        Assert.Contains("extip", Assert.Single(bad.FormatErrors(CultureInfo.GetCultureInfo("en"))));
    }

    [Theory]
    [InlineData("", 10)]
    [InlineData("vlan-name-too-long", 10)]
    public void Vlan_ValidatesName(string name, int id) => Assert.False(SnippetGenerator.Vlan(new VlanInput(name, "port1", id, "10.0.0.1/24")).Ok);
}

public sealed class ToolTextTests
{
    [Fact]
    public void ItalianTranslation_HasEveryKey()
    {
        var it = CultureInfo.GetCultureInfo("it-IT");
        var en = CultureInfo.GetCultureInfo("en");
        var missing = ToolText.Keys().Where(k => ToolText.Get(k, it) == ToolText.Get(k, en) && !k.StartsWith("Export.Col.", StringComparison.Ordinal)
            && k is not ("Snippet.Import" or "AUD-045.Detail")).ToList();
        Assert.True(missing.Count == 0, "Not translated: " + string.Join(", ", missing));
    }

    [Fact]
    public void IpRules()
    {
        Assert.True(IpAddressRules.IsNetmask(System.Net.IPAddress.Parse("255.255.255.0")));
        Assert.False(IpAddressRules.IsNetmask(System.Net.IPAddress.Parse("255.0.255.0")));
        Assert.True(IpAddressRules.TryParseSubnet("10.1.2.3/8", out var ip, out var p) && p == 8 && ip.ToString() == "10.1.2.3");
        Assert.False(IpAddressRules.TryParseIPv4("010.1.1.1", out _));
        Assert.False(IpAddressRules.IsPublicIPv4(System.Net.IPAddress.Parse("100.64.1.1")));
        Assert.True(IpAddressRules.IsPublicIPv4(System.Net.IPAddress.Parse("8.8.8.8")));
    }
